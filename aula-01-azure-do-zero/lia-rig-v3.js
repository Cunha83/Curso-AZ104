/**
 * Grafts the 1:1 pixel-aligned Medium-Shot Mouth (`x: 435..590, y: 330..435`)
 * from a Nano Banana Medium-Shot Viseme render onto a Nano Banana Medium-Shot Body render.
 * Because all Frontal Medium-Shot renders were generated by Nano Banana from the exact same
 * 1024x1024 reference image, the face and mouth coordinates match at 1:1 scale with zero shift.
 */
function applyMedMouthToBody(bodyBuf, visemeHeadBuf) {
  const w = 1024;
  const out = Buffer.from(bodyBuf);
  const cx = 513, cy = 315, rx = 128, ry = 128;
  for (let y = 185; y <= 445; y++) {
    for (let x = 385; x <= 642; x++) {
      const nx = (x - cx) / rx, ny = (y - cy) / ry;
      const r2 = nx * nx + ny * ny;
      if (r2 >= 1.0) continue;
      const r = Math.sqrt(r2);
      const wFeather = r < 0.78 ? 1.0 : 0.5 * (1 + Math.cos(Math.PI * (r - 0.78) / 0.22));
      const idx = (y * w + x) * 3;
      for (let c = 0; c < 3; c++) {
        out[idx + c] = Math.round(bodyBuf[idx + c] * (1 - wFeather) + visemeHeadBuf[idx + c] * wFeather);
      }
    }
  }
  return out;
}

/**
 * Grafts 100%-opaque Nano Banana eyelids (`HALF` or `FULL`) onto the eye sockets of any
 * Close-Up, Frontal Medium-Shot, or Point-Left Medium-Shot buffer without touching the mouth.
 */
function applyNanoBananaBlink(baseBuf, blinkHalfBuf, blinkFullBuf, mode, blinkWeight) {
  if (!blinkWeight || blinkWeight <= 0.15) return baseBuf;
  const w = 1024;
  const out = Buffer.from(baseBuf);
  const isFull = blinkWeight >= 0.65;
  const srcLid = (isFull || !blinkHalfBuf) ? blinkFullBuf : blinkHalfBuf;

  let eyes;
  if (mode === 'CLOSE') {
    eyes = [
      { cx: 422, cy: 318, rx: 68, ry: 44 },
      { cx: 602, cy: 318, rx: 68, ry: 44 }
    ];
  } else if (mode === 'POINT_LEFT') {
    // 3/4 turned head eye sockets in med_point_screen.jpg / lia_nb_med_point_left_blink
    eyes = [
      { cx: 432, cy: 268, rx: 46, ry: 32 },
      { cx: 542, cy: 268, rx: 50, ry: 32 }
    ];
  } else {
    // Frontal Medium Shot eye sockets
    eyes = [
      { cx: 454, cy: 274, rx: 48, ry: 32 },
      { cx: 571, cy: 274, rx: 48, ry: 32 }
    ];
  }

  for (const eye of eyes) {
    for (let y = eye.cy - eye.ry; y <= eye.cy + eye.ry; y++) {
      for (let x = eye.cx - eye.rx; x <= eye.cx + eye.rx; x++) {
        const nx = (x - eye.cx) / eye.rx;
        const ny = (y - eye.cy) / eye.ry;
        const r = Math.sqrt(nx * nx + ny * ny);
        if (r >= 1.0) continue;
        const radialEnv = r < 0.74 ? 1.0 : 0.5 * (1 + Math.cos(Math.PI * (r - 0.74) / 0.26));
        const idx = (y * w + x) * 3;
        for (let c = 0; c < 3; c++) {
          out[idx + c] = Math.round(baseBuf[idx + c] * (1 - radialEnv) + srcLid[idx + c] * radialEnv);
        }
      }
    }
  }
  return out;
}

