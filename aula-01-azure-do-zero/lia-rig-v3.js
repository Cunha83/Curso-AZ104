  /**
   * Renders a 1024x1024 RGB raw buffer using 100% Native Nano Banana textures:
   * @param {Object} state
   * @param {'MED'|'CLOSE'} state.shot - Camera framing ('MED' waist-up or 'CLOSE' head-and-shoulders)
   * @param {string} state.viseme - One of: 'REST','MBP','FV','OU_50','OU','EI_25','EI_50','EI','A_75','A','SMILE'
   * @param {number} state.blink - Eyelid closure weight in [0.0, 1.0] (0=open, 0.5=half, 1.0=closed)
   * @param {'REST'|'PREP'|'PALM'|'ENUM1'|'ENUM2'|'POINT_LEFT'} state.gesture - Body gesture in Medium Shot
   * @param {number} state.gazeLeft - Gaze + head turn toward left screen in [0.0, 1.0]
   * @param {number} state.elbowDeg - Used to detect intermediate preparation/recovery phase
   * @param {number} state.liftY - Used to detect intermediate preparation/recovery phase
   */
  renderAvatarBuffer(state) {
    const shot = state.shot || 'MED';
    const viseme = this.closeVisemes[state.viseme] ? state.viseme : 'REST';
    const blinkQ = (state.blink || 0) >= 0.65 ? 1.0 : ((state.blink || 0) >= 0.20 ? 0.5 : 0.0);
    const gesture = state.gesture || 'REST';
    const gazeLeft = state.gazeLeft || 0;
    const isPointLeft = (gesture === 'POINT_LEFT' || gazeLeft >= 0.55);
    const isPrepPhase = (
      gesture === 'PREP' ||
      state.gesturePhase === 'preparation' ||
      state.gesturePhase === 'recovery' ||
      (!isPointLeft && Math.abs(state.liftY || 0) >= 18) ||
      (isPointLeft && gazeLeft > 0.05 && gazeLeft < 0.55)
    );

    const effectiveGesture = isPrepPhase ? 'PREP' : (isPointLeft ? 'POINT_LEFT' : gesture);
    const cacheKey = `${shot}|${effectiveGesture}|${viseme}|${blinkQ}`;
    if (this.frameCache.has(cacheKey)) {
      return this.frameCache.get(cacheKey);
    }

    let buf;
    if (shot === 'CLOSE') {
      buf = Buffer.from(this.closeVisemes[viseme]);
      if (blinkQ > 0) {
        buf = applyNanoBananaBlink(buf, this.closeBlinkHalf, this.closeBlinkFull, 'CLOSE', blinkQ);
      }
    } else if (effectiveGesture === 'POINT_LEFT') {
      // 100% Native Nano Banana 3/4 Point-Left + Gaze-Left render with phonetic visemes and blink
      buf = Buffer.from(this.medPointLeftVisemes[viseme] || this.medPointLeftVisemes.REST);
      if (blinkQ > 0) {
        buf = applyNanoBananaBlink(buf, this.medPointLeftBlink, this.medPointLeftBlink, 'POINT_LEFT', blinkQ);
      }
    } else {
      // 100% Native Nano Banana Frontal Medium Shot (REST, PREP, PALM, ENUM1, ENUM2)
      const baseBody = this.medBodyPoses[effectiveGesture] || this.medBodyPoses.REST;
      const visemeHead = this.medVisemeHeads[viseme] || this.medVisemeHeads.REST;
      buf = applyMedMouthToBody(baseBody, visemeHead);
      if (blinkQ > 0) {
        buf = applyNanoBananaBlink(buf, this.medBlinkHalf, this.medBlinkFull, 'MED', blinkQ);
      }
    }

    if (this.frameCache.size > 180) {
      const firstKey = this.frameCache.keys().next().value;
      this.frameCache.delete(firstKey);
    }
    this.frameCache.set(cacheKey, buf);
    return buf;
  }

